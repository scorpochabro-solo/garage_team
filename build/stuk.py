def payload():
    """Compact JSON for stuk.js. p: pages [href, name]; c: causes [title, text, page|null, request words|0];
    z: zones [label, words]; s: symptoms with contexts [key, label, request text, diag page, causes, zones, swatch]."""
    _check()
    pages = {}
    for key in PAGES:
        path, name = _page(key)
        pages[key] = [D.BASE + path, name]
    causes = {k: [t, x, p, w or 0] for k, (t, x, p, w) in CAUSES.items()}
    symptoms = {}
