# ---------- checks and payload ----------
def _page(key):
    path = PAGES[key]
    svc = D.BY_PATH.get(path)
    if svc is None:
        raise ValueError(f"stuk: нет страницы услуги {path} ({key})")
    if any(bad in path for bad in FORBIDDEN):
        raise ValueError(f"stuk: подсказка не должна вести на {path}")
    return path, svc.get("nav_name") or svc["h1"]


def _check():
    used = set()
    for s in SYMPTOMS:
        if s["icon"] not in OWN_ICONS:
            icon(s["icon"])                      # raises on an unknown icon
        for c in s["contexts"]:
            where = "{где}" in c["say"]
            if where != bool(c["zones"]):
                raise ValueError(f"stuk: {s['key']}/{c['key']}: «{{где}}» в тексте должно быть ровно тогда, когда есть зоны")
            if c["zones"] and not s["q3"]:
                raise ValueError(f"stuk: {s['key']}: зоны есть, а вопроса «Где?» нет")
            _page(c["diag"])
            lists = [c["causes"], *c["zones"].values()]
            for z in c["zones"]:
                if z not in ZONES:
                    raise ValueError(f"stuk: неизвестная зона {z}")
            for lst in lists:
                if not 2 <= len(lst) <= 4:
                    raise ValueError(f"stuk: {s['key']}/{c['key']}: причин должно быть 2–4, а не {len(lst)}")
                for k in lst:
                    if k not in CAUSES:
                        raise ValueError(f"stuk: неизвестная причина {k}")
                    used.add(k)
    for k in CAUSES:
        if k not in used:
            raise ValueError(f"stuk: причина {k} нигде не используется")
        if CAUSES[k][2]:
            _page(CAUSES[k][2])
    for s, c, z, _ in PRESETS:
        sym = next(x for x in SYMPTOMS if x["key"] == s)
        cx = next(x for x in sym["contexts"] if x["key"] == c)
        if z and z not in cx["zones"]:
            raise ValueError(f"stuk: пример {s}/{c}/{z}: такой зоны нет")


